#[test]
fn test_zip_bomb_protection() {
    let mut buf = Vec::new();
    {
        let mut zip = ZipWriter::new(Cursor::new(&mut buf));
        let options =
            SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
        zip.start_file("huge.txt", options).unwrap();
        // write 50,000 zeros which compress to ~50 bytes (ratio > 500:1)
        zip.write_all(&vec![0u8; 50_000]).unwrap();
        zip.finish().unwrap();
    }

    let limits = ContainerLimits {
        max_file_count: 10,
        max_uncompressed_bytes: 1_000_000,
        max_compression_ratio: 50.0, // strict 50:1 threshold
    };

    let err =
        AppContainer::open_with_limits(Cursor::new(buf), limits).expect_err("must fail zip bomb");
    match err {
        ContainerError::ZipBomb(ratio, thresh) => {
            assert!(ratio > thresh);
        }
        other => panic!("expected ZipBomb error, got: {other:?}"),
    }
}

