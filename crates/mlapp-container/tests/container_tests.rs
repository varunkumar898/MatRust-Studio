fn create_mock_mlapp_bytes(release: &str, include_mat: bool) -> Vec<u8> {
    let mut buf = Vec::new();
    {
        let mut zip = ZipWriter::new(Cursor::new(&mut buf));
        let options =
            SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);

        // [Content_Types].xml
        zip.start_file("[Content_Types].xml", options).unwrap();
        zip.write_all(b"<?xml version=\"1.0\" encoding=\"UTF-8\"?><Types></Types>")
            .unwrap();

        // metadata/coreProperties.xml
        zip.start_file("metadata/coreProperties.xml", options)
            .unwrap();
        let core = r#"<?xml version="1.0" encoding="UTF-8"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties"
                   xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:title>SineWaveApp</dc:title>
    <dc:creator>TestAuthor</dc:creator>
    <dc:description>A mock sine wave generator app for testing</dc:description>
    <cp:version>1.2.0</cp:version>
</cp:coreProperties>"#;
        zip.write_all(core.as_bytes()).unwrap();

        // appdesigner/app.xml
        zip.start_file("appdesigner/app.xml", options).unwrap();
        let app_xml = format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by MATLAB App Designer ({}) -->
<appdata xmlns="http://schemas.mathworks.com/appdesigner/2018">
    <UIFigure Name="UIFigure" Position="100 100 640 480">
        <Button Name="RunButton" Text="Calculate" Position="20 400 100 30" />
    </UIFigure>
</appdata>"#,
            release
        );
        zip.write_all(app_xml.as_bytes()).unwrap();

        // matlab/document.xml
        zip.start_file("matlab/document.xml", options).unwrap();
        let doc_xml = r#"<?xml version="1.0" encoding="UTF-8"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
    <![CDATA[
    classdef SineWaveApp < matlab.apps.AppBase
        properties (Access = public)
            UIFigure  matlab.ui.Figure
            RunButton matlab.ui.control.Button
        end
        methods (Access = private)
            function RunButtonPushed(app, event)
                t = 0:0.01:1;
                y = sin(2*pi*5*t);
            end
        end
    end
    ]]>
</w:document>"#;
        zip.write_all(doc_xml.as_bytes()).unwrap();

        // thumbnail image
        zip.start_file("metadata/thumbnail.png", options).unwrap();
        zip.write_all(&[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A])
            .unwrap();

        if include_mat {
            zip.start_file("matlab/embedded_data.mat", options).unwrap();
            zip.write_all(b"MATLAB 5.0 MAT-file mock binary data")
                .unwrap();
        }

        zip.finish().unwrap();
    }
    buf
}

fn create_mock_mlappinstall_bytes() -> Vec<u8> {
    let mut buf = Vec::new();
    {
        let mut zip = ZipWriter::new(Cursor::new(&mut buf));
        let options =
            SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);

        // metadata/manifest.xml
        zip.start_file("metadata/manifest.xml", options).unwrap();
        let manifest = r#"<?xml version="1.0" encoding="UTF-8"?>
<manifest>
    <name>SignalAnalyzerPackage</name>
    <version>2.0.4</version>
    <author>Jane Doe</author>
    <summary>Analyzes spectral components</summary>
    <description>Full description of the signal analyzer application.</description>
    <requiredToolbox>Signal Processing Toolbox</requiredToolbox>
    <requiredToolbox>DSP System Toolbox</requiredToolbox>
</manifest>"#;
        zip.write_all(manifest.as_bytes()).unwrap();

        // Inner .mlapp
        zip.start_file("apps/SignalAnalyzer.mlapp", options)
            .unwrap();
        let inner_mlapp = create_mock_mlapp_bytes("R2021a", false);
        zip.write_all(&inner_mlapp).unwrap();

        // Screenshot
        zip.start_file("resources/screenshot.png", options).unwrap();
        zip.write_all(&[0x89, b'P', b'N', b'G']).unwrap();

        zip.finish().unwrap();
    }
    buf
}

#[test]
fn test_inspect_mlapp_structure() {
    let bytes = create_mock_mlapp_bytes("R2021a", true);
    let mut container = AppContainer::open(Cursor::new(bytes)).expect("open mlapp");

    assert_eq!(container.package_type(), PackageType::Mlapp);

    let report = container.inspect().expect("inspect report");
    assert_eq!(report.manifest.app_name, "SineWaveApp");
    assert_eq!(report.manifest.author, "TestAuthor");
    assert_eq!(report.manifest.version, "1.2.0");
    assert_eq!(
        report.manifest.detected_matlab_release.as_deref(),
        Some("R2021a")
    );

    // Verify role classification
    assert!(report
        .entries
        .iter()
        .any(|e| e.role == EntryRole::Code && e.name == "matlab/document.xml"));
    assert!(report
        .entries
        .iter()
        .any(|e| e.role == EntryRole::UiLayout && e.name == "appdesigner/app.xml"));
    assert!(report
        .entries
        .iter()
        .any(|e| e.role == EntryRole::Thumbnail));
    assert!(report
        .entries
        .iter()
        .any(|e| e.role == EntryRole::BinaryData));

    // Verify unsupported binary flag
    assert_eq!(report.unsupported_features.len(), 1);
    assert!(report.unsupported_features[0].contains("unsupported-binary"));
}

