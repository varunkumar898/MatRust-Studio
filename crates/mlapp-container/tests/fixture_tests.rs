use mlapp_container::{AppContainer, PackageType};
use mlapp_lang::{
    analyze_compatibility, extract_code_from_document_xml, parse_app_classdef, CompatStatus,
};
use mlapp_ui::{parse_app_xml, ComponentKind, Rect};
use std::fs::File;
use std::io::{Cursor, Write};
use zip::write::SimpleFileOptions;
use zip::ZipWriter;

fn build_test_app(release: &str, out_path: &str, is_hazardous: bool) {
    let mut buf = Vec::new();
    {
        let mut zip = ZipWriter::new(Cursor::new(&mut buf));
        let opt = SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);

        zip.start_file("[Content_Types].xml", opt).unwrap();
        zip.write_all(b"<?xml version=\"1.0\" encoding=\"UTF-8\"?><Types></Types>")
            .unwrap();

        zip.start_file("metadata/coreProperties.xml", opt).unwrap();
        let core = format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties"
                   xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:title>FixtureApp_{}</dc:title>
    <dc:creator>FixtureBuilder</dc:creator>
    <cp:version>1.0.0</cp:version>
</cp:coreProperties>"#,
            release
        );
        zip.write_all(core.as_bytes()).unwrap();

        zip.start_file("appdesigner/app.xml", opt).unwrap();
        let app = format!(
            r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by MATLAB App Designer ({}) -->
<appdata>
  <UIFigure Name="UIFigure" Position="[100, 100, 800, 600]">
    <Panel Name="SettingsPanel" Position="20, 20, 300, 560">
      <Button Name="StartBtn" Text="Start" Position="10, 480, 120, 30" ButtonPushedFcn="StartBtnPushed" />
      <NumericEditField Name="ThresholdField" Value="0.85" Position="10, 430, 120, 22" />
    </Panel>
    <UIAxes Name="MainAxes" Position="340, 60, 440, 480" />
  </UIFigure>
</appdata>"#,
            release
        );
        zip.write_all(app.as_bytes()).unwrap();

        zip.start_file("matlab/document.xml", opt).unwrap();
        let code_body = if is_hazardous {
            r#"
classdef FixtureApp < matlab.apps.AppBase
    properties (Access = public)
        UIFigure matlab.ui.Figure
        StartBtn matlab.ui.control.Button
    end
    methods (Access = private)
        function StartBtnPushed(app, event)
            system("dir");
            eval("delete file.txt");
            web("http://example.com");
        end
    end
end
"#
        } else {
            r#"
classdef FixtureApp < matlab.apps.AppBase
    properties (Access = public)
        UIFigure matlab.ui.Figure
        StartBtn matlab.ui.control.Button
    end
    methods (Access = private)
        function StartBtnPushed(app, event)
            t = linspace(0, 1, 100);
            y = sin(2 * pi * 5 * t);
            plot(app.MainAxes, t, y);
            disp("Done");
        end
    end
end
"#
        };

        let doc = format!(
            r#"<?xml version="1.0" encoding="utf-8"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
<![CDATA[
{}
]]>
</w:document>"#,
            code_body
        );
        zip.write_all(doc.as_bytes()).unwrap();

        zip.start_file("metadata/thumbnail.png", opt).unwrap();
        zip.write_all(&[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A])
            .unwrap();

        zip.finish().unwrap();
    }

    if let Some(parent) = std::path::Path::new(out_path).parent() {
        std::fs::create_dir_all(parent).unwrap();
    }
    std::fs::write(out_path, buf).unwrap();
}

#[test]
fn test_fixtures_generation_and_inspection() {
    let fixture_path = "fixtures/sample_apps/r2021a_sample.mlapp";
    build_test_app("R2021a", fixture_path, false);

    let file = File::open(fixture_path).expect("open fixture");
    let mut container = AppContainer::open(file).expect("container open");

    assert_eq!(container.package_type(), PackageType::Mlapp);
    let report = container.inspect().expect("inspect");
    assert_eq!(report.manifest.app_name, "FixtureApp_R2021a");
    assert_eq!(
        report.manifest.detected_matlab_release.as_deref(),
        Some("R2021a")
    );

    // Verify UI component parsing from the fixture's app.xml
    let app_xml = container
        .read_entry_to_string("appdesigner/app.xml")
        .expect("read app.xml");
    let ui_tree = parse_app_xml(&app_xml).expect("parse ui tree");

    assert_eq!(ui_tree.kind, ComponentKind::UIFigure);
    assert_eq!(ui_tree.position, Rect::new(100.0, 100.0, 800.0, 600.0));

    let btn = ui_tree.find_by_name("StartBtn").expect("find StartBtn");
    assert_eq!(btn.kind, ComponentKind::Button);
    assert_eq!(
        btn.callbacks.get("buttonpushedfcn").map(|s| s.as_str()),
        Some("StartBtnPushed")
    );

    let axes = ui_tree.find_by_name("MainAxes").expect("find MainAxes");
    assert_eq!(axes.kind, ComponentKind::UIAxes);

    // Verify check-compat finds real functions
    let doc_xml = container
        .read_entry_to_string("matlab/document.xml")
        .expect("read doc.xml");
    let code = extract_code_from_document_xml(&doc_xml).expect("extract code");
    let class_def = parse_app_classdef(&code).expect("parse classdef");
    let compat = analyze_compatibility(&class_def);

    assert_eq!(compat.compatibility_score, 100);
    assert_eq!(compat.status, CompatStatus::Runs);
    assert!(compat.supported_functions.contains(&"linspace".to_string()));
    assert!(compat.supported_functions.contains(&"sin".to_string()));
    assert!(compat.supported_functions.contains(&"plot".to_string()));
    assert!(compat.supported_functions.contains(&"disp".to_string()));
    assert!(compat.hazardous_functions.is_empty());
}

#[test]
fn test_hazardous_fixture_compatibility() {
    let fixture_path = "fixtures/sample_apps/hazardous_sample.mlapp";
    build_test_app("R2024b", fixture_path, true);

    let file = File::open(fixture_path).expect("open hazardous fixture");
    let mut container = AppContainer::open(file).expect("container open");

    let doc_xml = container
        .read_entry_to_string("matlab/document.xml")
        .expect("read doc.xml");
    let code = extract_code_from_document_xml(&doc_xml).expect("extract code");
    let class_def = parse_app_classdef(&code).expect("parse classdef");
    let compat = analyze_compatibility(&class_def);

    assert_eq!(compat.status, CompatStatus::Unsupported);
    assert!(compat.compatibility_score <= 50);
    assert!(compat.hazardous_functions.contains(&"system".to_string()));
    assert!(compat.hazardous_functions.contains(&"eval".to_string()));
    assert!(compat.hazardous_functions.contains(&"web".to_string()));
}

