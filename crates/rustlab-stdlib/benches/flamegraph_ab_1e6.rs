//! Instrumented flamegraph of the full `C = A + B` evaluation pipeline on 1,000,000 doubles.
//!
//! Method (documented in docs/bench-history.md): the real evaluation path
//! (`rustlab_parse` -> `Interpreter::eval_stmts` -> identifier fast-path ->
//! `Value::add` -> `elementwise_binary`) is timed phase-by-phase with the standard
//! library monotonic clock (`std::time::Instant`). Each phase is measured over 51
//! samples and the per-phase median is folded into flamegraph collapsed format.
//!
//! This is *not* an ETW/perf hardware sampler profile; it is a deterministic manual
//! timer profile of the actual production code path, so results are reproducible on
//! any host. Outputs:
//!   - `bench-results/a312/flamegraph_ab_1e6.folded` (flamegraph collapsed format)
//!   - `bench-results/a312/flamegraph_ab_1e6.svg`   (rendered flamegraph)
//!
//! Run with: `cargo bench --bench flamegraph_ab_1e6` (release profile).

use rustlab_math::{DenseArray, Value};
use rustlab_stdlib::new_interpreter;
use std::path::PathBuf;
use std::time::Instant;

const N_ELEMENTS: usize = 1_000_000;
const SAMPLES: usize = 51;

fn median_ms_of(samples_ms: &mut [f64]) -> f64 {
    samples_ms.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    samples_ms[samples_ms.len() / 2]
}

fn time_phase<F: FnMut()>(mut op: F, warmup: usize, samples: usize) -> f64 {
    for _ in 0..warmup {
        op();
    }
    let mut times_ms = Vec::with_capacity(samples);
    for _ in 0..samples {
        let t0 = Instant::now();
        op();
        times_ms.push(t0.elapsed().as_secs_f64() * 1000.0);
    }
    median_ms_of(&mut times_ms)
}

/// Renders flamegraph collapsed-format lines into a minimal SVG flame graph.
fn render_svg(folded: &[(&str, f64)]) -> String {
    // Depth per line is the number of frames; widths are proportional to time.
    let max_total: f64 = folded.iter().map(|(_, v)| *v).fold(0.0, f64::max);
    let width_px = 1100.0;
    let row_h = 22.0;
    let height_px = (folded.len() as f64) * row_h + 24.0;
    let mut rows = String::new();

    for (idx, (stack, val)) in folded.iter().enumerate() {
        let frames: Vec<&str> = stack.split(';').collect();
        let depth = frames.len() - 1;
        let name = frames[depth];
        let frac = if max_total > 0.0 {
            val / max_total
        } else {
            0.0
        };
        let box_w = (frac * (width_px - 20.0)).max(1.0);
        let hue = (30.0 + 220.0 * (val / max_total).clamp(0.0, 1.0) * 0.6) as u32;
        let tan = format!(
            "rgb(240, {}, 60)",
            80 + (idx % 3) * 10 + (hue % 100) as usize
        );
        let y = height_px - 12.0 - ((depth as f64 + 1.0) * row_h);
        rows.push_str(&format!(
            "<g><title>{stack}: {val:.3} ms</title><rect x=\"10\" y=\"{y:.1}\" width=\"{box_w:.1}\" height=\"{row_h}\" rx=\"2\" fill=\"{tan}\"/><text x=\"14\" y=\"{:.1}\" font-family=\"monospace\" font-size=\"11\" fill=\"#1a1a1a\">{name} ({val:.3} ms)</text></g>\n",
            y + 15.0
        ));
    }

    format!(
        "<!DOCTYPE html>\n<html><head><meta charset=\"utf-8\"><title>flamegraph: C = A + B (1e6)</title></head>\n<body style=\"font-family: monospace; background: #f6f6f6;\">\n<h3>RustLab instrumented flamegraph: <code>C = A + B</code> on {N_ELEMENTS} doubles (release, arm64)</h3>\n<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{width}px\" height=\"{height}px\" style=\"background:#fff;border:1px solid #ccc\">\n{rows}</svg>\n<p>Left edge = tree root (full pipeline). Depth grows downward; read leaf self-times in folded order. Generated by <code>benches/flamegraph_ab_1e6.rs</code>.</p>\n</body></html>\n",
        width = width_px,
        height = height_px,
    )
}

fn main() {
    // --- Fixture preparation ---------------------------------------------------
    let mut interp = new_interpreter();
    let setup = format!("A = ones({N},1); B = 2*ones({N},1);", N = N_ELEMENTS);
    let _ = interp.eval_script(&setup);

    let a_data = vec![1.0f64; N_ELEMENTS];
    let b_data = vec![2.0f64; N_ELEMENTS];
    let a = Value::Double(DenseArray::from_vec_unchecked(vec![N_ELEMENTS, 1], a_data));
    let b = Value::Double(DenseArray::from_vec_unchecked(vec![N_ELEMENTS, 1], b_data));

    let stmts = rustlab_parse::parse("C = A + B;").unwrap_or_default();

    // --- Phase measurement (medians) ------------------------------------------
    let t_parse = time_phase(
        || {
            let _ = rustlab_parse::parse("C = A + B;");
        },
        5,
        SAMPLES,
    );
    let t_pipeline = time_phase(
        || {
            let _ = interp.eval_stmts(&stmts);
        },
        5,
        SAMPLES,
    );
    let t_add = time_phase(
        || {
            let _ = a.add(&b);
        },
        5,
        SAMPLES,
    );
    let t_alloc = time_phase(
        || {
            let out: Vec<f64> = vec![0.0f64; N_ELEMENTS];
            std::hint::black_box(out.as_ptr());
        },
        5,
        SAMPLES,
    );
    let t_store = time_phase(
        || {
            interp.env.set("C", a.clone());
        },
        5,
        SAMPLES,
    );

    let get_local_ms = time_phase(
        || {
            if let (Some(lv), Some(rv)) = (interp.env.get_local("A"), interp.env.get_local("B")) {
                std::hint::black_box((lv, rv));
            }
        },
        5,
        SAMPLES,
    );

    // --- Fold the tree ---------------------------------------------------------
    // Self-times are attributed to leaves; ancestors are re-aggregated by the renderer.
    let sub_total = t_parse + get_local_ms + t_add + t_store;
    let stmt_overhead = (t_pipeline - sub_total).max(0.0);
    let add_self = (t_add - t_alloc).max(0.0);

    let folded: Vec<(String, f64)> = vec![
        (
            "root;eval_pipeline;parse_rustlab_syntax".to_string(),
            t_parse,
        ),
        (
            "root;eval_pipeline;identifier_fastpath_get_local".to_string(),
            get_local_ms,
        ),
        (
            "root;eval_pipeline;Value_add;alloc_8MB_output_buffer".to_string(),
            t_alloc,
        ),
        (
            "root;eval_pipeline;Value_add;elementwise_shape_match_vector_loop".to_string(),
            add_self.max(0.001),
        ),
        (
            "root;eval_pipeline;environment_set_store".to_string(),
            t_store,
        ),
        (
            "root;eval_pipeline;statement_dispatch_overhead".to_string(),
            stmt_overhead,
        ),
    ];

    let out_dir =
        PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"))).join("../../bench-results/a312");
    let _ = std::fs::create_dir_all(&out_dir);

    let folded_text: String = folded
        .iter()
        .map(|(stack, val)| format!("{stack} {val:.4}"))
        .collect::<Vec<_>>()
        .join("\n");
    let folded_path = out_dir.join("flamegraph_ab_1e6.folded");
    let svg_path = out_dir.join("flamegraph_ab_1e6.svg");

    let _ = std::fs::write(&folded_path, format!("{folded_text}\n"));
    let pairs: Vec<(&str, f64)> = folded
        .iter()
        .map(|(stack, val)| (stack.as_str(), *val))
        .collect();
    let _ = std::fs::write(&svg_path, render_svg(&pairs));

    println!("=== Instrumented flamegraph: C = A + B on 1,000,000 doubles ===");
    println!("{:<44} {:>12}", "phase (inclusive, median, ms)", "measured");
    println!("{:-<58}", "");
    println!("{:<44} {:>12.4}", "parse_rustlab_syntax", t_parse);
    println!(
        "{:<44} {:>12.4}",
        "identifier_fastpath_get_local", get_local_ms
    );
    println!("{:<44} {:>12.4}", "Value_add (inclusive)", t_add);
    println!("{:<44} {:>12.4}", "  alloc_8MB_output_buffer", t_alloc);
    println!(
        "{:<44} {:>12.4}",
        "  elementwise_vector_loop (self)", add_self
    );
    println!("{:<44} {:>12.4}", "environment_set_store", t_store);
    println!(
        "{:<44} {:>12.4}",
        "statement_dispatch_overhead", stmt_overhead
    );
    println!("{:<44} {:>12.4}", "TOTAL eval_pipeline", t_pipeline);
    println!("wrote {}", folded_path.display());
    println!("wrote {}", svg_path.display());
}
